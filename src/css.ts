import { dirname, join, relative, sep } from 'node:path';

export interface CssOptions {
  outputDir: string;
  cssFile: string;
  fontDisplay: string;
}

const FONT_FACE = /@font-face\s*\{[^}]*\}/gi;
const URL_PATTERN = /url\(\s*(['"]?)(.*?)\1\s*\)/g;
const FONT_DISPLAY = /font-display\s*:\s*[^;}]*;?/gi;

/** Path of `<outputDir>/<fileName>` as seen from the stylesheet, with forward slashes. */
export function fontUrl(fileName: string, outputDir: string, cssFile: string): string {
  return relative(dirname(cssFile), join(outputDir, fileName)).split(sep).join('/');
}

/** The `@font-face { … }` blocks of a stylesheet, in order. */
export function extractFontFaces(css: string): string[] {
  return css.match(FONT_FACE) ?? [];
}

function rewriteUrl(raw: string, quote: string, opts: CssOptions): string {
  if (/^[a-z][a-z0-9+.-]*:/i.test(raw) || raw.startsWith('/')) {
    return `url(${quote}${raw}${quote})`;
  }
  const cut = raw.search(/[?#]/);
  const pathPart = cut === -1 ? raw : raw.slice(0, cut);
  const suffix = cut === -1 ? '' : raw.slice(cut);
  const fileName = pathPart.split(/[\\/]/).pop() ?? pathPart;
  const target = fontUrl(fileName, opts.outputDir, opts.cssFile) + suffix;
  const useQuote = quote || (/[\s'"()]/.test(target) ? '"' : '');
  return `url(${useQuote}${target}${useQuote})`;
}

/** Points each `src: url()` at the written file and sets `font-display`. */
export function rewriteFontFace(block: string, opts: CssOptions): string {
  let result = block.replace(URL_PATTERN, (_match, quote: string, raw: string) => rewriteUrl(raw, quote, opts));
  const display = `font-display: ${opts.fontDisplay};`;
  if (/font-display\s*:/i.test(result)) {
    return result.replace(FONT_DISPLAY, display);
  }
  result = result.replace(/\s*\}$/, '');
  return `${result}\n  ${display}\n}`;
}

/** Every kit's `@font-face` blocks, rewritten, as one stylesheet. */
export function mergeStylesheets(stylesheets: string[], opts: CssOptions): string {
  const blocks = stylesheets.flatMap(extractFontFaces).map((block) => rewriteFontFace(block, opts));
  return `/* Generated by Everything Fonts Web Font Build */\n\n${blocks.join('\n\n')}\n`;
}
